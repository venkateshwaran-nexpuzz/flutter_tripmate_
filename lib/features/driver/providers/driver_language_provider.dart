/// Supported Languages for Driver Mobile App
enum DriverLanguage {
  tamil('ta', 'தமிழ்', '🇮🇳', 'Tamil'),
  english('en', 'English', '🇬🇧', 'English'),
  hindi('hi', 'हिन्दी', '🇮🇳', 'Hindi'),
  malayalam('ml', 'മലയാളം', '🇮🇳', 'Malayalam'),
  telugu('te', 'తెలుగు', '🇮🇳', 'Telugu'),
  kannada('kn', 'ಕನ್ನಡ', '🇮🇳', 'Kannada');

  final String code;
  final String nativeName;
  final String flag;
  final String englishName;

  const DriverLanguage(this.code, this.nativeName, this.flag, this.englishName);

  static DriverLanguage fromCode(String code) {
    return DriverLanguage.values.firstWhere(
      (lang) => lang.code == code,
      orElse: () => DriverLanguage.tamil,
    );
  }
}

