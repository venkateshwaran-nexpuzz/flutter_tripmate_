const String _prefKey = 'driver_app_language_code';

class DriverLanguageNotifier extends StateNotifier<DriverLanguage> {
  DriverLanguageNotifier() : super(DriverLanguage.tamil) {
    _loadLanguage();
  }

  Future<void> _loadLanguage() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final savedCode = prefs.getString(_prefKey);
      if (savedCode != null) {
        state = DriverLanguage.fromCode(savedCode);
      }
    } catch (_) {
      // Fallback to default (tamil)
    }
  }

  Future<void> setLanguage(DriverLanguage language) async {
    state = language;
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_prefKey, language.code);
    } catch (_) {}
  }

  /// Translate a given key to active language
  String tr(String key) {
    final langMap = _translations[state.code] ?? _translations['ta']!;
    return langMap[key] ?? _translations['en']?[key] ?? key;
  }
}

/// Global provider for Driver App Language
final driverLanguageProvider = StateNotifierProvider<DriverLanguageNotifier, DriverLanguage>((ref) {
  return DriverLanguageNotifier();
});

/// Universal alias for all modules (Student, Driver, Incharge)
typedef AppLanguage = DriverLanguage;
final appLanguageProvider = driverLanguageProvider;

/// Convenience helper function to easily translate text in any ConsumerWidget:
/// `ref.tr('greeting')`
extension DriverTrExtension on WidgetRef {
  String tr(String key) {
    final currentLang = watch(driverLanguageProvider);
    final langMap = _translations[currentLang.code] ?? _translations['ta']!;
    return langMap[key] ?? _translations['en']?[key] ?? key;
  }
}
